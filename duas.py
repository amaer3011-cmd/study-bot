def pick(cat: str = "all", exclude: int | None = None, rnd=None) -> int:
    """يرجّع فهرس دعاء عشوائي من الفئة (all = الكل)، ومش نفس exclude لو فيه غيره."""
    import random
    rnd = rnd or random
    idxs = [i for i, (_, _, c) in enumerate(DUA_ITEMS) if cat == "all" or c == cat]
    if exclude in idxs and len(idxs) > 1:
        idxs.remove(exclude)
    return rnd.choice(idxs)


